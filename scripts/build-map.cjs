const corrections = new Map([
 ['赋总量：时间可整除时赋工作总量为效率的最小公倍数', {text:'赋总量：各人的单独完成时间为正整数时，可将工作总量赋为这些完成时间的最小公倍数，从而得到整数效率；也可以将总量设为1。',reason:'原文“效率的最小公倍数”改为“完成时间的最小公倍数”。'}],
 ['容斥：两集合|A∪B|=|A|+|B|−|A∩B|；三集合注意加回交集并减三重交集', {text:'容斥：|A∪B|=|A|+|B|−|A∩B|；三集合为 |A∪B∪C|=|A|+|B|+|C|−|A∩B|−|A∩C|−|B∩C|+|A∩B∩C|。',reason:'三集合并集先减去两两交集，再加回三重交集。'}],
 ['必要要件与充分要件：题干定义所列条件均需核对；区分“必须具备”与“具备即可”', {text:'必要要件与充分要件：按定义中的“且／或”组合条件；“且”要求全部具备，“或”按其选言含义判断。区分“必须具备”与“具备即可”。',reason:'补充且／或边界，避免将备选条件也误当作必须同时具备。'}]
]);
const lookup = new Map(mapping.map(([title,id,module,lessonIds,category])=>[title,{title,id,module,lessonIds,category}]));
let section='',topic;const topics=[];
for(const [index,line] of source.split(/\r?\n/).entries()) {
 if(line.startsWith('## ')) section=line.slice(3);
 else if(line.startsWith('### ')) {
  const title=line.slice(4),config=lookup.get(title);
  if(!config)throw Error('请为新专题配置模块与课程：'+title);
  topic={...config,sourceSection:section,sourceLine:index+1,points:[]};topics.push(topic);
 } else if(line.startsWith('#### ')) {
  if(!topic)throw Error('知识点缺少专题');
  const original=line.slice(5),correction=corrections.get(original);
  topic.points.push({id:topic.id+'-'+(topic.points.length+1),text:correction?.text||original,sourceText:original,sourceLine:index+1,correction:correction?.reason||null});
 }
}
if(topics.length!==mapping.length)throw Error('专题配置与源文件不一致');
const lessons=require('../data').lessons;
for(const t of topics)for(const id of t.lessonIds)if(!lessons.some(l=>l.id===id&&l.module===t.module))throw Error('课程映射无效：'+id);
const mappedIds=topics.flatMap(t=>t.lessonIds);
const uncovered=lessons.filter(l=>!mappedIds.includes(l.id));
if(uncovered.length)throw Error('课程未映射到知识地图：'+uncovered.map(l=>l.id).join(', '));
for(const t of topics)t.lessons=t.lessonIds.map(id=>{const l=lessons.find(x=>x.id===id);return {id:l.id,title:l.title};});
const meta={source:sourceName,sha256:createHash('sha256').update(source).digest('hex'),topics:topics.length,points:topics.reduce((n,t)=>n+t.points.length,0),corrections:topics.flatMap(t=>t.points).filter(p=>p.correction).length};
fs.writeFileSync(path.join(root,'knowledge-map.js'),'/* Generated by scripts/build-map.cjs from '+sourceName+' */\n(function(root){const data='+JSON.stringify({meta,topics},null,2)+';root.KNOWLEDGE_MAP=data;if(typeof module!=="undefined"&&module.exports)module.exports=data;})(typeof window!=="undefined"?window:globalThis);\n');
console.log(`知识地图：${meta.topics} 个专题，${meta.points} 条要点，${meta.corrections} 处校正。`);
