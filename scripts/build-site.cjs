const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
const marker = path.join(output, '.xingzhi-build');
const files = ['index.html', 'styles.css', 'app.js', 'bank.js', 'data.js', 'knowledge-map.js', 'domain.js', 'real-questions.js', 'icon.svg'];
// Only replace output created by this script, never an unrelated directory.
if (fs.existsSync(output)) {
  if (fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(marker)) throw Error('dist 已存在且不是本站构建目录，请先移走该目录。');
  fs.rmSync(output, { recursive: true });
}
fs.mkdirSync(output);
fs.writeFileSync(marker, 'Generated by scripts/build-site.cjs\n');
for (const file of files) fs.copyFileSync(path.join(root, file), path.join(output, file));
fs.cpSync(path.join(root, 'question-bank'), path.join(output, 'question-bank'), { recursive: true });
fs.writeFileSync(path.join(output, '.nojekyll'), '');
const meta = JSON.parse(fs.readFileSync(path.join(output, 'question-bank/metadata.json'), 'utf8'));
let bytes = 0, count = 0;
function scan(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(file);
    else { bytes += fs.statSync(file).size; count++; }
  }
}
scan(output);
if (bytes >= 1024 ** 3) throw Error('发布包超过 GitHub Pages 的 1 GB 限制。');
console.log(`发布文件：${output}\n${meta.total} 道题，${meta.papers} 套试卷，${count} 个文件，${(bytes / 1024 ** 2).toFixed(1)} MiB。`);
console.log('仅包含网站与题库；不包含学习记录、原始下载文件或测试日志。');
